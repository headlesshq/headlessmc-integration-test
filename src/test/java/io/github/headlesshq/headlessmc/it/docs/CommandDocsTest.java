package io.github.headlesshq.headlessmc.it.docs;

import io.github.headlesshq.headlessmc.it.FileChange;
import io.github.headlesshq.headlessmc.it.Recording;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

class CommandDocsTest {
    private static final FileChange CONFIG = new FileChange("hmc/config.properties", FileChange.Kind.ADDED, 10L, "a", null, null);

    private static final List<String> CI_LABELS = List.of(
        "jar linux-x64", "jar linux-arm64", "jar windows-x64", "jar windows-arm64", "jar macos-arm64", "jar macos-x64",
        "native linux-x64", "native linux-arm64", "native windows-x64", "native macos-arm64", "native macos-x64"
    );

    @TempDir
    Path dir;

    @Test
    void writesPagePerTestClassAndIndex() throws IOException {
        record("jar", "linux", "x64", "ConfigTest.setWritesConfigFile",
            step("config set a 1", 0, "Set a to 1", "", CONFIG),
            step("config get b", 2, "", "Unknown `b`"));
        record("jar", "linux", "x64", "HelpTest.helpForCommand-_config_", step("help config", 0, "Usage: config"));

        List<Path> pages = CommandDocs.generate(dir.resolve("recordings"), dir.resolve("out"));

        assertThat(pages).extracting(path -> path.getFileName().toString()).containsExactly("config.md", "help.md", "index.md");
        assertThat(Files.readString(dir.resolve("out/config.md"))).isEqualTo("""
            # Config

            !!! info "Auto-generated from integration tests for hmc 1.2.3"
                Generated by `./gradlew generateDocs` from the recordings of `ConfigTest`.
                Output is shown for `jar linux-x64`, other platforms get their own tab where their output differs.

            ## Set writes config file

            `ConfigTest.setWritesConfigFile`

            ```console
            $ hmc config set a 1
            Set a to 1
            ```

            ```text title="Files changed"
            hmc/
            └── config.properties  (added)
            ```

            ```console
            $ hmc config get b
            ```

            ```text title="stderr"
            Unknown `b`
            ```

            Exit code `2`.

            No files changed.
            """);
        assertThat(Files.readString(dir.resolve("out/help.md"))).contains("## Help for command: `config`");
        assertThat(Files.readString(dir.resolve("out/index.md")))
            .contains("| [Config](config.md) | 1 |")
            .contains("| [Help](help.md) | 1 |");
    }

    @Test
    void showsOnlyCanonicalOutputIfPlatformsOnlyDifferInColumnWidthAndFileSizes() throws IOException {
        record("native", "windows", "x64", "ConfigTest.ls",
            step("config ls", 0, "name     value\na        1", "",
                new FileChange("hmc/config.properties", FileChange.Kind.ADDED, 12L, "b", null, null)));
        record("jar", "linux", "x64", "ConfigTest.ls", step("config ls", 0, "name   value\na      1", "", CONFIG));

        CommandDocs.generate(dir.resolve("recordings"), dir.resolve("out"));

        String page = Files.readString(dir.resolve("out/config.md"));
        assertThat(page).doesNotContain("===").contains("name   value\na      1").doesNotContain("Only recorded");
    }

    @Test
    void addsTabsWherePlatformsDiffer() throws IOException {
        record("jar", "macos", "arm64", "JavaTest.ls", step("java ls", 0, "macos"));
        record("native", "linux", "x64", "JavaTest.ls", step("java ls", 0, "native"));
        record("jar", "linux", "x64", "JavaTest.ls", step("java ls", 0, "linux"));
        record("jar", "windows", "x64", "JavaTest.ls", step("java ls", 0, "linux"));

        CommandDocs.generate(dir.resolve("recordings"), dir.resolve("out"));

        assertThat(Files.readString(dir.resolve("out/java.md"))).endsWith("""
            `JavaTest.ls`

            ===! "jar linux-x64, jar windows-x64"

                ```console
                $ hmc java ls
                linux
                ```

                No files changed.

            === "jar macos-arm64"

                ```console
                $ hmc java ls
                macos
                ```

                No files changed.

            === "native linux-x64"

                ```console
                $ hmc java ls
                native
                ```

                No files changed.
            """);
    }

    @Test
    void startsNewTabSetForEachConsecutiveDifferingStep() throws IOException {
        record("jar", "linux", "x64", "ConfigTest.setThenGet", step("config set a 1", 0, "set linux"), step("config get a", 0, "get linux"));
        record("native", "windows", "x64", "ConfigTest.setThenGet", step("config set a 1", 0, "set windows"), step("config get a", 0, "get windows"));

        CommandDocs.generate(dir.resolve("recordings"), dir.resolve("out"));

        String page = Files.readString(dir.resolve("out/config.md"));
        assertThat(page)
            .contains("""
                ===! "jar linux-x64"

                    ```console
                    $ hmc config set a 1
                    set linux
                    ```

                    No files changed.

                === "native windows-x64"

                    ```console
                    $ hmc config set a 1
                    set windows
                    ```

                    No files changed.

                ===! "jar linux-x64"

                    ```console
                    $ hmc config get a
                    get linux
                    ```
                """)
            .contains("=== \"native windows-x64\"\n\n    ```console\n    $ hmc config get a\n");
    }

    @Test
    void addsTabsPerPlatformIfCommandsDiffer() throws IOException {
        record("jar", "linux", "x64", "LaunchTest.launch", step("launch a", 0, "a"));
        record("native", "linux", "x64", "LaunchTest.launch", step("launch b", 0, "b"));
        record("native", "linux", "x64", "LaunchTest.jarOnly", step("launch c", 0, "c"));

        CommandDocs.generate(dir.resolve("recordings"), dir.resolve("out"));

        String page = Files.readString(dir.resolve("out/launch.md"));
        assertThat(page)
            .contains("!!! note \"Only recorded on native linux-x64\"")
            .contains("===! \"jar linux-x64\"\n\n    ```console\n    $ hmc launch a\n")
            .contains("=== \"native linux-x64\"\n\n    ```console\n    $ hmc launch b\n");
    }

    @Test
    void regeneratingGivesSameOutputAndRemovesStalePages() throws IOException {
        record("jar", "linux", "x64", "ConfigTest.ls", step("config ls", 0, "out"));
        record("native", "linux", "x64", "ConfigTest.ls", step("config ls", 0, "native"));
        Path out = Files.createDirectories(dir.resolve("out"));
        Files.writeString(out.resolve("stale.md"), "stale");

        CommandDocs.generate(dir.resolve("recordings"), out);
        String first = Files.readString(out.resolve("config.md"));
        CommandDocs.generate(dir.resolve("recordings"), out);

        assertThat(Files.readString(out.resolve("config.md"))).isEqualTo(first);
        assertThat(out.resolve("stale.md")).doesNotExist();
    }

    @Test
    void usesLongerFenceIfOutputContainsBackticks() throws IOException {
        record("jar", "linux", "x64", "HelpTest.help", step("help", 0, "```\ncode\n```"));

        CommandDocs.generate(dir.resolve("recordings"), dir.resolve("out"));

        assertThat(Files.readString(dir.resolve("out/help.md"))).contains("````console\n$ hmc help\n```\ncode\n```\n````\n");
    }

    @Test
    void collapsesTabTitlesWithoutHidingPlatforms() {
        List<String> nativeWindows = List.of("native windows-x64");
        List<String> others = CI_LABELS.stream().filter(label -> !nativeWindows.contains(label)).toList();
        List<String> jar = CI_LABELS.stream().filter(label -> label.startsWith("jar ")).toList();
        List<String> nativeImages = CI_LABELS.stream().filter(label -> label.startsWith("native ")).toList();

        assertThat(CommandDocs.tabTitle(others, CI_LABELS)).isEqualTo("all except native windows-x64");
        assertThat(CommandDocs.tabTitle(nativeWindows, CI_LABELS)).isEqualTo("native windows-x64");
        assertThat(CommandDocs.tabTitle(jar, CI_LABELS)).isEqualTo("jar (all)");
        assertThat(CommandDocs.tabTitle(nativeImages, CI_LABELS)).isEqualTo("native (all)");
        assertThat(CommandDocs.tabTitle(List.of("jar linux-x64", "jar linux-arm64", "jar macos-arm64", "native linux-x64"), CI_LABELS))
            .isEqualTo("jar linux-x64, jar linux-arm64, jar macos-arm64, native linux-x64");
        assertThat(CommandDocs.tabTitle(List.of("jar windows-x64", "jar windows-arm64"), CI_LABELS.subList(0, 6)))
            .isEqualTo("jar windows-arm64, jar windows-x64");
    }

    @Test
    void notesOnWhichPlatformsTestWasRecordedWithoutHidingPlatforms() {
        List<String> jar = CI_LABELS.stream().filter(label -> label.startsWith("jar ")).toList();
        List<String> windows = CI_LABELS.stream().filter(label -> label.contains("windows")).toList();

        assertThat(CommandDocs.recordedOn(jar, CI_LABELS)).isEqualTo("Only recorded on jar");
        assertThat(CommandDocs.recordedOn(CI_LABELS.subList(0, 10), CI_LABELS)).isEqualTo("Not recorded on native macos-x64");
        assertThat(CommandDocs.recordedOn(windows, CI_LABELS)).isEqualTo("Only recorded on jar windows-arm64, jar windows-x64, native windows-x64");
    }

    @Test
    void marksTestsRecordedOnOneTypeOnly() throws IOException {
        for (String label : CI_LABELS) {
            String[] parts = label.split("[ -]");
            record(parts[0], parts[1], parts[2], "HelpTest.help", step("help", 0, "help"));
            if (parts[0].equals("jar")) {
                record(parts[0], parts[1], parts[2], "JavaTest.marksJavaRunningTheJarAsCurrent",
                    step("java", 0, label.equals("jar windows-x64") ? "windows" : "current"));
            }
        }

        CommandDocs.generate(dir.resolve("recordings"), dir.resolve("out"));

        assertThat(Files.readString(dir.resolve("out/java.md")))
            .contains("!!! note \"Only recorded on jar\"")
            .contains("===! \"all except jar windows-x64\"")
            .contains("=== \"jar windows-x64\"");
    }

    private void record(String type, String os, String arch, String test, Recording.Step... steps) {
        String platform = os + "-" + arch;
        new Recording(Recording.SCHEMA_VERSION, test, platform, os, arch, "1.2.3",
            new Recording.Executable(type, "hmc"), List.of(steps))
            .write(dir.resolve("recordings").resolve("recordings-" + type + "-" + platform));
    }

    private static Recording.Step step(String command, int exitCode, String stdout) {
        return step(command, exitCode, stdout, "");
    }

    private static Recording.Step step(String command, int exitCode, String stdout, String stderr, FileChange... files) {
        return new Recording.Step(List.of(command.split(" ")), "hmc " + command, exitCode, false, 1, stdout, stderr, List.of(files));
    }

}
